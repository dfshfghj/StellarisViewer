let language = DEFAULT_LANGUAGE;

export function getLanguage() {
    return language;
}

export function setLanguage(value) {
    language = SUPPORTED_LANGUAGES.includes(value) ? value : DEFAULT_LANGUAGE;
    if (typeof document !== 'undefined') document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    return language;
}

export function t(key, values = {}) {
    const template = MESSAGES[language]?.[key] ?? MESSAGES.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? `{${name}}`));
}

export function translateDocument(root = document) {
    for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
    for (const element of root.querySelectorAll('[data-i18n-title]')) {
        const value = t(element.dataset.i18nTitle);
        element.title = value;
        element.setAttribute('aria-label', value);
    }
    document.title = t('app.title');
}
